
    create table tb_autor (
        id bigint generated by default as identity,
        nacionalidade varchar(255),
        nome varchar(255) not null,
        primary key (id)
    );

    create table tb_avaliacao (
        data date not null,
        nota integer not null,
        livro_id bigint not null,
        membro_id bigint not null,
        comentario varchar(255),
        primary key (livro_id, membro_id)
    );

    create table tb_carteirinha (
        data_emissao date not null,
        membro_id bigint not null,
        numero varchar(255) not null,
        primary key (membro_id)
    );

    create table tb_categoria (
        id bigint generated by default as identity,
        nome varchar(255) not null,
        primary key (id)
    );

    create table tb_emprestimo (
        data_devolucao date,
        data_emprestimo date not null,
        data_prevista_devolucao date not null,
        id bigint generated by default as identity,
        livro_id bigint not null,
        membro_id bigint not null,
        status varchar(255) not null check ((status in ('ATIVO','DEVOLVIDO','ATRASADO'))),
        primary key (id)
    );

    create table tb_livro (
        ano_publicacao integer,
        autor_id bigint not null,
        id bigint generated by default as identity,
        titulo varchar(255) not null,
        primary key (id)
    );

    create table tb_livro_categoria (
        categoria_id bigint not null,
        livro_id bigint not null,
        primary key (categoria_id, livro_id)
    );

    create table tb_membro (
        id bigint generated by default as identity,
        email varchar(255) not null,
        nome varchar(255) not null,
        senha varchar(255) not null,
        tipo varchar(255) not null check ((tipo in ('ALUNO','PROFESSOR'))),
        primary key (id)
    );

    create table tb_membro_role (
        membro_id bigint not null,
        role_id bigint not null,
        primary key (membro_id, role_id)
    );

    create table tb_role (
        id bigint generated by default as identity,
        authority varchar(255) not null unique,
        primary key (id)
    );

    create index idx_emprestimo_membro_id
       on tb_emprestimo (membro_id);

    create index idx_emprestimo_livro_id
       on tb_emprestimo (livro_id);

    create index idx_livro_autor_id
       on tb_livro (autor_id);

    alter table if exists tb_avaliacao
       add constraint fk_avaliacao_livro
       foreign key (livro_id)
       references tb_livro;

    alter table if exists tb_avaliacao
       add constraint fk_avaliacao_membro
       foreign key (membro_id)
       references tb_membro;

    alter table if exists tb_carteirinha
       add constraint fk_carteirinha_membro
       foreign key (membro_id)
       references tb_membro;

    alter table if exists tb_emprestimo
       add constraint fk_emprestimo_livro
       foreign key (livro_id)
       references tb_livro;

    alter table if exists tb_emprestimo
       add constraint fk_emprestimo_membro
       foreign key (membro_id)
       references tb_membro;

    alter table if exists tb_livro
       add constraint fk_livro_autor
       foreign key (autor_id)
       references tb_autor;

    alter table if exists tb_livro_categoria
       add constraint fk_livro_categoria_categoria
       foreign key (categoria_id)
       references tb_categoria;

    alter table if exists tb_livro_categoria
       add constraint fk_livro_categoria_livro
       foreign key (livro_id)
       references tb_livro;

    alter table if exists tb_membro_role
       add constraint fk_membro_role_role
       foreign key (role_id)
       references tb_role;

    alter table if exists tb_membro_role
       add constraint fk_membro_role_membro
       foreign key (membro_id)
       references tb_membro;
